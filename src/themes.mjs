function semanticTokenColors(s) {
  return {
    parameter: { foreground: s.param, italic: true },
    property: s.property,
    'property.declaration': s.property,
    enumMember: s.constant,
    'variable.defaultLibrary': s.builtin,
    'class.defaultLibrary': s.builtin,
    'interface.defaultLibrary': s.builtin,
    'type.defaultLibrary': s.builtin,
    class: s.type,
    interface: s.type,
    type: s.type,
    struct: s.type,
    enum: s.type,
    namespace: s.type,
    typeParameter: { foreground: s.type, italic: true },
    function: s.func,
    method: s.func,
    'function.defaultLibrary': s.func,
    decorator: s.decorator,
    macro: s.decorator,
    selfKeyword: { foreground: s.self, italic: true },
    selfParameter: { foreground: s.self, italic: true },
    '*.deprecated': { strikethrough: true },
  };
}

/** The full VS Code color theme JSON for one variant */
export function buildTheme(v) {
  return {
    $schema: 'vscode://schemas/color-theme',
    name: v.label,
    type: v.type,
    semanticHighlighting: true,
    colors: uiColors(v),
    tokenColors: tokenColors(v.syntax),
    semanticTokenColors: semanticTokenColors(v.syntax),
  };
}
